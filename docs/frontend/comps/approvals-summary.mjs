#!/usr/bin/env node
// The §3.7 approval summary that appears in `built/README.md` — GENERATED from
// `approvals.json`, which is the ledger the gate is read out of.
//
//     node docs/frontend/comps/approvals-summary.mjs        # rewrite the README block
//     node docs/frontend/comps/approvals-summary.mjs --check # exit 1 if it is stale
//
// **Why this exists.** W11's review round 3 found the README's prose claiming, two sections
// apart, both that every cockpit composition matched its approved screen AND that the gate
// was "UNPASSED: 4 of 8 compositions await a ruling" with "the W11 cockpit screens do not
// exist yet". Both sentences were hand-maintained; one of them stopped being true when the
// operator's rulings landed, and nothing noticed. A summary a human retypes is a summary
// that drifts from the ledger, so this one is computed from it and pinned by
// `test/comps-captures.test.js`.
//
// Nothing here can manufacture an approval: it only restates `status`, `decidedBy` and
// `builtCaptures` as they are recorded. Approving a composition is still a human act
// performed by editing `approvals.json` (§3.7).

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
export const LEDGER = path.join(HERE, 'approvals.json')
export const README = path.join(HERE, 'built', 'README.md')

export const BEGIN = '<!-- approvals:begin — generated by approvals-summary.mjs; edit approvals.json -->'
export const END = '<!-- approvals:end -->'

/** The gate's verdict word — `entryGate` opens with PASSED or UNPASSED (the test pins it). */
const verdict = (entryGate) => String(entryGate).trim().split(/[\s—:.]/)[0]

/** Render the block body (between the markers) from a parsed ledger. */
export function renderApprovalSummary(ledger, { builtDir = path.join(HERE, 'built') } = {}) {
  const comps = ledger.compositions
  const approved = comps.filter((c) => c.status === 'approved')
  const committed = new Set(
    fs.existsSync(builtDir) ? fs.readdirSync(builtDir).filter((f) => f.endsWith('.png')) : [],
  )

  const rows = comps.map((c) => {
    const shots = (c.builtCaptures ?? []).filter((f) => committed.has(path.basename(f)))
    const captures = (c.builtCaptures ?? []).length === 0
      ? 'not built yet'
      : shots.length === (c.builtCaptures ?? []).length
        ? `${shots.length} committed (${c.builtBy ?? '—'})`
        : `${shots.length} of ${(c.builtCaptures ?? []).length} committed — MISSING`
    return `| \`${c.id}\` | ${c.status} | ${c.decidedBy ?? '—'} | ${captures} |`
  })

  return [
    '',
    `**The §3.7 entry gate is ${verdict(ledger.entryGate)}: ${approved.length} of `
      + `${comps.length} compositions are approved** (four canonical states × two`,
    'viewports). `approvals.json` is the authority — its `entryGate` field carries the full',
    'ruling and each entry carries its own `decidedBy`/`decidedIn`.',
    '',
    '| composition | status | ruled by | built captures |',
    '|---|---|---|---|',
    ...rows,
    '',
    'Approving a composition is a human act by construction — it means editing its entry in',
    '`approvals.json`. `test/comps-captures.test.js` checks that `entryGate` agrees with the',
    'entries, that every entry with built captures carries a `sideBySide` record, and that',
    'this block still matches what the ledger says.',
    '',
  ].join('\n')
}

/** Splice a freshly rendered block into the README text. */
export function spliceReadme(readme, block) {
  const start = readme.indexOf(BEGIN)
  const end = readme.indexOf(END)
  if (start < 0 || end < 0 || end < start) {
    throw new Error(`built/README.md is missing the ${BEGIN} / ${END} markers`)
  }
  return readme.slice(0, start + BEGIN.length) + block + readme.slice(end)
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const ledger = JSON.parse(fs.readFileSync(LEDGER, 'utf8'))
  const current = fs.readFileSync(README, 'utf8')
  const next = spliceReadme(current, renderApprovalSummary(ledger))
  if (process.argv.includes('--check')) {
    if (next !== current) {
      console.error('built/README.md\'s approval summary is stale — run:\n'
        + '    node docs/frontend/comps/approvals-summary.mjs')
      process.exit(1)
    }
    console.log('approval summary is current')
  } else {
    fs.writeFileSync(README, next)
    console.log(`wrote ${path.relative(process.cwd(), README)}`)
  }
}
